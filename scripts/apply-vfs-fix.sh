#!/bin/sh
# apply-vfs-fix.sh — set up the VFS overlay that fixes the os_workgroup module
# (the "unexpected type name 'OS_object'" wall). This is the verified partial
# breakthrough toward pure-Swift Foundation/UIKit. See references/LIMITATIONS.md §1.
#
# It installs a patched os.modulemap (os_workgroup gains `header "os/object.h"`)
# and a VFS overlay mapping the SDK's modulemap path to the patched copy.
# After running, add these flags to every module build:
#   -Xcc -ivfsoverlay -Xcc /opt/ios-toolchain/vfs/overlay.yaml
set -e
SDK="${1:-/opt/ios-toolchain/iPhoneOS26.5.sdk}"
VFS=/opt/ios-toolchain/vfs
SKILL_DIR="$(cd "$(dirname "$0")/.." && pwd)"
mkdir -p "$VFS"

# 1. Patched os.modulemap — generated by patching the user's LOCAL SDK modulemap
#    (we do NOT ship Apple's modulemap; it is derived on-device from the SDK you
#    already have). This keeps the skill free of Apple-copyrighted material.
python3 - "$SDK" "$VFS" <<'PY'
import sys
sdk, vfs = sys.argv[1], sys.argv[2]
src = open(f"{sdk}/usr/include/os.modulemap").read()
patched = src.replace(
    'module os_workgroup [system] {\n  module workgroup {\n    header "os/workgroup.h"',
    'module os_workgroup [system] {\n  module workgroup {\n    header "os/object.h"\n    header "os/workgroup.h"')
assert patched != src, "patch anchor not found — SDK modulemap layout changed"
open(f"{vfs}/os.modulemap", "w").write(patched)
PY

# 2. VFS overlay JSON (absolute SDK path required).
cat > "$VFS/overlay.yaml" <<EOF
{
  "version": 0, "case-sensitive": true,
  "roots": [
    { "type": "file",
      "name": "$SDK/usr/include/os.modulemap",
      "external-contents": "$VFS/os.modulemap" }
  ]
}
EOF

echo "VFS overlay ready: $VFS/overlay.yaml"
echo "Use with:  -Xcc -ivfsoverlay -Xcc $VFS/overlay.yaml"
echo "(fixes os_workgroup; Dispatch still needs the header-patch approach — see LIMITATIONS §1)"
